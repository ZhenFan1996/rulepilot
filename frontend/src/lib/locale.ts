export type TranslationKey = keyof typeof messages['zh-CN']
export type TranslationCatalog = Readonly<Record<TranslationKey, string>>
type Variables = Record<string, string | number>

function preferredLocale(): AppLocale {
  if (typeof window === 'undefined') return FALLBACK_LOCALE
  const saved = window.localStorage.getItem(STORAGE_KEY)
  if (saved === 'en' || saved === 'zh-CN') return saved
  return FALLBACK_LOCALE
}

const activeLocale = ref<AppLocale>(preferredLocale())
const englishMessages = ref<TranslationCatalog | null>(null)
let englishMessagesPromise: Promise<TranslationCatalog> | undefined

export function preloadLocale(value: AppLocale) {
  if (value !== 'en' || englishMessages.value) return Promise.resolve()
  englishMessagesPromise ??= import('./locale.en').then((module) => {
    const catalog: TranslationCatalog = module.default
    englishMessages.value = catalog
    return catalog
  })
  return englishMessagesPromise.then(() => undefined)
}

// A saved English preference is restored before any component can call setLocale.
// Start its lazy catalog immediately so the selected language cannot render with Chinese fallback copy after refresh.
void preloadLocale(activeLocale.value)

function applyDocumentLanguage(value: AppLocale) {
  if (typeof document !== 'undefined') document.documentElement.lang = value
}

applyDocumentLanguage(activeLocale.value)

export function normalizeLocale(value: unknown): AppLocale {
  return value === 'en' || value === 'en-US' || value === 'en-GB' ? 'en' : FALLBACK_LOCALE
}

export function setLocale(value: AppLocale) {
  void preloadLocale(value)
  activeLocale.value = value
  if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, value)
  applyDocumentLanguage(value)
}

export function useLocale() {
  function t(key: TranslationKey, variables: Variables = {}) {
    const catalog = activeLocale.value === 'en' ? englishMessages.value : messages['zh-CN']
    return (catalog?.[key] ?? messages['zh-CN'][key]).replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`))
  }

  return { locale: activeLocale, setLocale, t }
}
