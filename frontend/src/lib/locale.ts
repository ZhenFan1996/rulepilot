type TranslationKey = keyof typeof messages['zh-CN']
type Variables = Record<string, string | number>

function preferredLocale(): AppLocale {
  if (typeof window === 'undefined') return FALLBACK_LOCALE
  const saved = window.localStorage.getItem(STORAGE_KEY)
  if (saved === 'en' || saved === 'zh-CN') return saved
  return FALLBACK_LOCALE
}

const activeLocale = ref<AppLocale>(preferredLocale())

function applyDocumentLanguage(value: AppLocale) {
  if (typeof document !== 'undefined') document.documentElement.lang = value
}

applyDocumentLanguage(activeLocale.value)

export function normalizeLocale(value: unknown): AppLocale {
  return value === 'en' || value === 'en-US' || value === 'en-GB' ? 'en' : FALLBACK_LOCALE
}

export function setLocale(value: AppLocale) {
  activeLocale.value = value
  if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, value)
  applyDocumentLanguage(value)
}

export function useLocale() {
  function t(key: TranslationKey, variables: Variables = {}) {
    return messages[activeLocale.value][key].replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`))
  }

  return { locale: activeLocale, setLocale, t }
}
